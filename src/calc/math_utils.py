"""Math utility functions with Google-style docstrings."""


def add_numbers(a: float, b: float) -> float:
    """Add two numbers together.

    Args:
        a: First number.
        b: Second number.

    Returns:
        Sum of ``a`` and ``b``.
    """
    return a + b


def multiply_numbers(a: float, b: float) -> float:
    """Multiply two numbers together.

    Args:
        a: First number.
        b: Second number.

    Returns:
        Product of ``a`` and ``b``.
    """
    return a * b
